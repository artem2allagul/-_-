# Вычисление силы гравитационного притяжения по закону всемирного тяготения Ньютона
# Формула: F = G * (m1 * m2) / r^2

# Ввод исходных данных с клавиатуры с помощью функции input()
# Строковые значения сразу преобразуются в вещественный тип float()
G = float(input('Введите гравитационную постоянную G (Н*м^2/кг^2): '))
m1 = float(input('Введите массу первого тела m1 (кг): '))
m2 = float(input('Введите массу второго тела m2 (кг): '))
r = float(input('Введите расстояние между телами r (м): '))

# Расчет силы гравитационного притяжения
# Степень записывается оператором ** (а не ^, как в математической записи)
F = G * (m1 * m2) / r ** 2

# Вывод результата с округлением вещественной части до 4 знаков после запятой
# с помощью f-строки и спецификатора формата {:.4f}
print(f'Сила гравитационного притяжения F = {F:.4f} Н')
